package backup

import (
	"bytes"
	"io"
	"testing"

	"github.com/klauspost/compress/zstd"
)

// TestStorageCompressionRejectsMalformedWeightTables prevents untrusted compressed artifacts from crashing the decoder.
func TestStorageCompressionRejectsMalformedWeightTables(t *testing.T) {
	t.Run("buffered", func(t *testing.T) {
		decoder, err := zstd.NewReader(nil)
		if err != nil {
			t.Fatal(err)
		}
		defer decoder.Close()
		if _, err := decoder.DecodeAll(malformedZstdTwoBlockFrame(), make([]byte, 100*1024)); err == nil {
			t.Fatal("malformed weight table accepted")
		}
	})
	t.Run("streaming", func(t *testing.T) {
		decoder, err := zstd.NewReader(bytes.NewReader(malformedZstdTwoBlockFrame()), zstd.WithDecoderConcurrency(1))
		if err != nil {
			t.Fatal(err)
		}
		defer decoder.Close()
		if _, err := io.ReadAll(decoder); err == nil {
			t.Fatal("malformed weight table accepted")
		}
	})
}

