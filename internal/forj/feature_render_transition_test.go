// TestFeatureDisabledRenderPreservesUnrelatedSource keeps ordinary application packages available during upgrades.
func TestFeatureDisabledRenderPreservesUnrelatedSource(t *testing.T) {
	usePrimitiveRendererRoot(t)
	config := &project.Config{ProjectName: "Feature transition", GoModuleName: "example.com/featuretransition", Render: project.RenderConfig{Components: project.Components{CLI: true}}}
	if err := writeProjectConfig(".goforj.yml", config); err != nil {
		t.Fatal(err)
	}
	sources := map[string]string{
		"internal/features/business.go":    "package features\nfunc Available() bool { return true }\n",
		"internal/features/manager_gen.go": "package features\nfunc BusinessSearch() {}\n",
		"app/wire/app.go":                  "package wire\ntype App struct{}\nfunc (app *App) Features() string { return \"business\" }\n",
	}
	for path, source := range sources {
		writePrimitiveRendererFile(t, path, source)
	}
	writePrimitiveRendererFile(t, "go.mod", "module example.com/featuretransition\n")
	if err := unitProjectRenderer(t).Render(ComponentRenderInput{components: project.Components{CLI: true}}); err != nil {
		t.Fatal(err)
	}
	for path, source := range sources {
		if strings.HasPrefix(path, "internal/features/") && readPrimitiveRendererFile(t, path) != source {
			t.Fatalf("render changed application source %s", path)
		}
	}
}

// TestFeatureRenderRemovalRefusesBeforeMutation retains actual generated ownership until the application migrates explicitly.
func TestFeatureRenderRemovalRefusesBeforeMutation(t *testing.T) {
	for _, test := range []struct{ name, path, source string }{
		{"manager", "internal/features/manager_gen.go", "// Code generated by forj generate --feature. DO NOT EDIT.\npackage features\n"},
		{"accessors", "internal/features/accessors_gen.go", "// Code generated by forj generate --feature. DO NOT EDIT.\npackage features\n"},
		{"Wire accessor", "app/wire/app.go", "package wire\nimport \"example.com/featuretransition/internal/features\"\ntype App struct{}\nfunc (app *App) Features() *features.Manager { return nil }\n"},
	} {
		t.Run(test.name, func(t *testing.T) {
			usePrimitiveRendererRoot(t)
			config := &project.Config{ProjectName: "Feature transition", GoModuleName: "example.com/featuretransition", Render: project.RenderConfig{Components: project.Components{CLI: true, Feature: true}}}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			writePrimitiveRendererFile(t, test.path, test.source)
			writePrimitiveRendererFile(t, "go.mod", "module example.com/featuretransition\n")
			writePrimitiveRendererFile(t, ".env", "FEATURE_DRIVER=memory\nOWNER=keep\n")
			paths := []string{".goforj.yml", "go.mod", ".env", test.path}
			before := primitiveRendererFileHashes(t, paths)
			err := unitProjectRenderer(t).Render(ComponentRenderInput{components: project.Components{CLI: true}})
			if err == nil || !strings.Contains(err.Error(), "cannot disable Feature") {
				t.Fatalf("removal=%v", err)
			}
			if !reflect.DeepEqual(before, primitiveRendererFileHashes(t, paths)) {
				t.Fatal("rejected removal changed owner files")
			}
		})
	}
}

// TestFeatureManagerAccessorRequiresExactType prevents name-only or nested-type matches from claiming user code.
func TestFeatureManagerAccessorRequiresExactType(t *testing.T) {
	for _, test := range []struct {
		name, source string
		want         bool
	}{
		{"typed", "import \"example.com/app/internal/features\"; type App struct{}; func (*App) Features() *features.Manager {return nil}", true},
		{"alias", "import flags \"example.com/app/internal/features\"; type App struct{}; func (*App) Features() *flags.Manager {return nil}", true},
		{"dot", "import . \"example.com/app/internal/features\"; type App struct{}; func (*App) Features() *Manager {return nil}", true},
		{"unrelated return", "type App struct{}; func (*App) Features() string {return \"business\"}", false},
		{"parameter only", "import \"example.com/app/internal/features\"; type App struct{}; func (*App) Features(manager *features.Manager) string {return \"business\"}", false},
		{"no result", "type App struct{}; func (*App) Features() {}", false},
		{"double pointer", "import \"example.com/app/internal/features\"; type App struct{}; func (*App) Features() **features.Manager {return nil}", false},
		{"unrelated import", "import \"example.com/business/features\"; type App struct{}; func (*App) Features() *features.Manager {return nil}", false},
		{"unrelated receiver", "import \"example.com/app/internal/features\"; type Business struct{}; func (*Business) Features() *features.Manager {return nil}", false},
		{"free function", "import \"example.com/app/internal/features\"; func Features() *features.Manager {return nil}", false},
	} {
		t.Run(test.name, func(t *testing.T) {
			file, err := parser.ParseFile(token.NewFileSet(), "app.go", "package wire\n"+test.source, 0)
			if err != nil {
				t.Fatal(err)
			}
			if got := featureManagerAccessor(file); got != test.want {
				t.Fatalf("accessor=%v, want %v", got, test.want)
			}
		})
	}
}
