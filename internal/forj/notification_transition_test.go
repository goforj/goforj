// TestNotificationLastAppRemovalRefusesResourceAndAccessorResidue protects both supported final-owner removal boundaries.
func TestNotificationLastAppRemovalRefusesResourceAndAccessorResidue(t *testing.T) {
	for _, resource := range []bool{false, true} {
		name := "accessor only"
		if resource {
			name = "resource package"
		}
		t.Run(name, func(t *testing.T) {
			root := usePrimitiveRendererRoot(t)
			app := project.DefaultNamedApp("billing")
			config := &project.Config{Render: project.RenderConfig{Components: project.Components{CLI: true}}, Apps: map[string]project.AppConfig{
				app.Name: {Components: project.Components{CLI: true, Notification: true}},
			}}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(app.WireDir, "app.go")
			if !resource {
				writePrimitiveRendererFile(t, path, "package wire\nimport \"example.com/app/internal/notifications\"\ntype App struct{}\nfunc (app *App) Notifications() *notifications.Manager { return nil }\n")
			}
			if resource {
				writePrimitiveRendererFile(t, "internal/notifications/manager_gen.go", "// Code generated by forj generate --notification. DO NOT EDIT.\npackage notifications\n")
			}
			before := appResourcePreflightSnapshot(t, root)
			result, err := unitProjectRenderer(t).RemoveApp(app)
			if err == nil || !strings.Contains(err.Error(), "last App using Notifications") || result.Changed() {
				t.Fatalf("last owner removal = %#v, %v", result, err)
			}
			if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
				t.Fatal("rejected final App removal changed files")
			}
		})
	}
}

// TestNotificationAccessorPreflightDistinguishesSyntaxFromUnrelatedText requires the typed App getter rather than a matching name.
func TestNotificationAccessorPreflightDistinguishesSyntaxFromUnrelatedText(t *testing.T) {
	usePrimitiveRendererRoot(t)
	renderer := projectRendererForTest(t, &project.Config{})
	const resourceImport = `import "example.com/app/internal/notifications"; `
	for _, test := range []struct {
		name, source  string
		want, invalid bool
	}{
		{name: "missing"},
		{name: "typed", source: resourceImport + "type App struct{}; func (*App) Notifications() *notifications.Manager {return nil}", want: true},
		{name: "value receiver", source: resourceImport + "type App struct{}; func (App) Notifications() *notifications.Manager {return nil}", want: true},
		{name: "alias", source: `import senders "example.com/app/internal/notifications"; type App struct{}; func (*App) Notifications() *senders.Manager {return nil}`, want: true},
		{name: "dot", source: `import . "example.com/app/internal/notifications"; type App struct{}; func (*App) Notifications() *Manager {return nil}`, want: true},
		{name: "named result", source: resourceImport + "type App struct{}; func (*App) Notifications() (manager *notifications.Manager) {return nil}", want: true},
		{name: "unrelated receiver", source: resourceImport + "type Observer struct{}; func (*Observer) Notifications() *notifications.Manager {return nil}"},
		{name: "unrelated observer", source: "type Observer struct{}; func (*Observer) Notifications() []string {return nil}"},
		{name: "any result", source: "type App struct{}; func (*App) Notifications() any {return nil}"},
		{name: "string result", source: "type App struct{}; func (*App) Notifications() string {return \"business\"}"},
		{name: "method parameter", source: resourceImport + "type App struct{}; func (*App) Notifications(manager *notifications.Manager) *notifications.Manager {return nil}"},
		{name: "variadic parameter", source: resourceImport + "type App struct{}; func (*App) Notifications(manager ...*notifications.Manager) *notifications.Manager {return nil}"},
		{name: "no result", source: "type App struct{}; func (*App) Notifications() {}"},
		{name: "multiple results", source: resourceImport + "type App struct{}; func (*App) Notifications() (*notifications.Manager, error) {return nil, nil}"},
		{name: "grouped results", source: resourceImport + "type App struct{}; func (*App) Notifications() (first, second *notifications.Manager) {return nil, nil}"},
		{name: "double pointer", source: resourceImport + "type App struct{}; func (*App) Notifications() **notifications.Manager {return nil}"},
		{name: "value result", source: resourceImport + "type App struct{}; func (*App) Notifications() notifications.Manager {panic(0)}"},
		{name: "unrelated import", source: `import "example.com/business/notifications"; type App struct{}; func (*App) Notifications() *notifications.Manager {return nil}`},
		{name: "blank import", source: `import _ "example.com/app/internal/notifications"; type App struct{}; func (*App) Notifications() *notifications.Manager {return nil}`},
		{name: "free function", source: resourceImport + "func Notifications() *notifications.Manager {return nil}"},
		{name: "comments", source: "// func (*App) Notifications() *notifications.Manager {return nil}\n"},
		{name: "strings", source: "const source = `func (*App) Notifications() *notifications.Manager {return nil}`"},
		{name: "invalid", source: "func (", invalid: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			path := filepath.Join(test.name, "app.go")
			if test.source != "" {
				writePrimitiveRendererFile(t, path, "package wire\n"+test.source)
			}
			got, err := renderer.notificationAccessorExists(path)
			if got != test.want || (err != nil) != test.invalid {
				t.Fatalf("accessor = %v, %v", got, err)
			}
		})
	}
}

// TestNotificationDisabledRenderPreservesOwnerPackage keeps a never-enabled namespace available to application code.
func TestNotificationDisabledRenderPreservesOwnerPackage(t *testing.T) {
	for _, appOnly := range []bool{false, true} {
		t.Run(map[bool]string{false: "project", true: "App"}[appOnly], func(t *testing.T) {
			usePrimitiveRendererRoot(t)
			config := &project.Config{ProjectName: "Existing", GoModuleName: "example.com/existing", Render: project.RenderConfig{Components: project.Components{CLI: true}}}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			writePrimitiveRendererFile(t, "go.mod", "module example.com/existing\n")
			sources := map[string]string{
				"internal/notifications/custom.go":        "package notifications\nfunc Send() {}\n",
				"internal/notifications/manager_gen.go":   "package notifications\nconst marker = `// Code generated by forj generate --notification. DO NOT EDIT.`\n",
				"internal/notifications/accessors_gen.go": "/* Owner documentation mentions generated resources.\n// Code generated by forj generate --notification. DO NOT EDIT.\n*/\npackage notifications\n",
			}
			for path, source := range sources {
				writePrimitiveRendererFile(t, path, source)
			}
			renderer := unitProjectRenderer(t)
			var err error
			if appOnly {
				err = renderer.RenderAppOnly(project.DefaultNamedApp("billing"), makeapp.RenderOptions{Components: project.Components{CLI: true}, SkipWire: true})
			} else {
				err = renderer.Render(ComponentRenderInput{components: project.Components{CLI: true}})
			}
			if err != nil {
				t.Fatal(err)
			}
			for path, source := range sources {
				if readPrimitiveRendererFile(t, path) != source {
					t.Fatalf("render changed owner file %s", path)
				}
			}
		})
	}
}

// TestNotificationGeneratedResidueRequiresLeadingMarker prevents examples and ordinary owner files from becoming framework ownership.
func TestNotificationGeneratedResidueRequiresLeadingMarker(t *testing.T) {
	const marker = "// Code generated by forj generate --notification. DO NOT EDIT."
	for _, test := range []struct {
		name, source string
		want         bool
	}{
		{"generated", marker + "\npackage notifications\n", true},
		{"generated CRLF", marker + "\r\npackage notifications\r\n", true},
		{"build constraint", "//go:build custom\n\n" + marker + "\npackage notifications\n", true},
		{"unmarked", "package notifications\nfunc Send() {}\n", false},
		{"string", "package notifications\nconst example = `" + marker + "`\n", false},
		{"comment", "/*\n" + marker + "\n*/\npackage notifications\n", false},
		{"suffix", marker + " is only an example\npackage notifications\n", false},
	} {
		for _, name := range []string{"manager_gen.go", "accessors_gen.go"} {
			t.Run(test.name+"/"+name, func(t *testing.T) {
				root := usePrimitiveRendererRoot(t)
				config := &project.Config{Render: project.RenderConfig{Components: project.Components{CLI: true}}}
				if err := writeProjectConfig(".goforj.yml", config); err != nil {
					t.Fatal(err)
				}
				path := filepath.Join("internal", "notifications", name)
				writePrimitiveRendererFile(t, path, test.source)
				renderer := unitProjectRenderer(t)
				got, err := renderer.workspace.notificationGeneratedResiduePath()
				if err != nil || (got != "") != test.want {
					t.Fatalf("residue=%q, %v", got, err)
				}
				if test.want {
					before := appResourcePreflightSnapshot(t, root)
					err := renderer.Render(ComponentRenderInput{components: project.Components{CLI: true}})
					if err == nil || !strings.Contains(err.Error(), "cannot disable Notifications") {
						t.Fatalf("render=%v", err)
					}
					if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
						t.Fatal("rejected render changed files")
					}
				}
			})
		}
	}
}

// TestNotificationLastAppRemovalPreservesUnmarkedNamespace leaves owner resources intact when the final capability has no generated residue.
func TestNotificationLastAppRemovalPreservesUnmarkedNamespace(t *testing.T) {
	usePrimitiveRendererRoot(t)
	app := project.DefaultNamedApp("billing")
	config := &project.Config{ProjectName: "Existing", GoModuleName: "example.com/existing", Render: project.RenderConfig{Components: project.Components{CLI: true}}, Apps: map[string]project.AppConfig{app.Name: {Components: project.Components{CLI: true, Notification: true}}}}
	if err := writeProjectConfig(".goforj.yml", config); err != nil {
		t.Fatal(err)
	}
	sources := map[string]string{
		"internal/notifications/custom.go":      "package notifications\nfunc Send() {}\n",
		"internal/notifications/manager_gen.go": "package notifications\nfunc OwnerManager() {}\n",
	}
	for path, source := range sources {
		writePrimitiveRendererFile(t, path, source)
	}
	writePrimitiveRendererFile(t, filepath.Join(app.WireDir, "app.go"), "package wire\ntype Observer struct{}\nfunc (*Observer) Notifications() []string {return nil}\n")
	if _, err := unitProjectRenderer(t).RemoveApp(app); err != nil {
		t.Fatal(err)
	}
	for path, source := range sources {
		if readPrimitiveRendererFile(t, path) != source {
			t.Fatalf("removal changed owner file %s", path)
		}
	}
}
