// TestAppRemovalResourceOwnershipPreservesSurvivingConsumers prevents App cleanup from deleting a shared owner's generated accessor.
func TestAppRemovalResourceOwnershipPreservesSurvivingConsumers(t *testing.T) {
	for _, test := range []struct {
		name, path string
		shared     bool
	}{
		{name: "shared owner", path: "internal/checkout/service.go"},
		{name: "removed owner", path: "app/billing/service.go"},
		{name: "surviving global accessor", path: "internal/checkout/service.go", shared: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			root, config := appResourcePreflightFixture(t)
			config.Apps = map[string]project.AppConfig{"billing": {Components: project.Components{CLI: true, Feature: true}}}
			config.Dev.Apps = map[string]project.DevApp{"billing": {}}
			config.Dev.Run = map[string]string{"billing": "go run ./cmd/billing"}
			environment := "FEATURE_DRIVER=memory\nBILLING_FEATURE_CHECKOUT_DRIVER=memory\n"
			if test.shared {
				config.Apps["reports"] = project.AppConfig{Components: project.Components{CLI: true, Feature: true}}
				environment += "REPORTS_FEATURE_CHECKOUT_DRIVER=memory\n"
			}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			for _, path := range []string{".env", ".env.example", ".env.host"} {
				writePrimitiveRendererFile(t, path, environment)
			}
			writePrimitiveRendererFile(t, test.path, "package owner\nimport \"example.com/ownership/internal/features\"\nfunc use(manager *features.Manager) { _ = manager.Checkout() }\n")
			if _, err := generate.GenerateProjectFiles(".", generate.GenerationSelectionFromComponents(config.Render.Components)); err != nil {
				t.Fatal(err)
			}
			renderer := unitProjectRenderer(t)
			renderer.config = config
			original := *config
			original.Apps = maps.Clone(config.Apps)
			original.Dev.Run = maps.Clone(config.Dev.Run)
			original.Dev.Apps = maps.Clone(config.Dev.Apps)
			before := appResourcePreflightSnapshot(t, root)
			_, err := renderer.RemoveApp(project.DefaultNamedApp("billing"))
			if test.name == "shared owner" {
				if err == nil || !strings.Contains(err.Error(), "reconcile resource names and surviving owner source") {
					t.Fatalf("removal guard = %v", err)
				}
				if renderer.config != config || !reflect.DeepEqual(*config, original) {
					t.Fatal("rejected removal changed config object")
				}
				if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
					t.Fatal("rejected removal changed project files")
				}
			} else {
				if err != nil {
					t.Fatal(err)
				}
				accessors := readPrimitiveRendererFile(t, generate.FeatureAccessorsPath)
				if strings.Contains(accessors, "Checkout()") != test.shared {
					t.Fatalf("surviving accessor presence = %t, want %t", strings.Contains(accessors, "Checkout()"), test.shared)
				}
			}
		})
	}
}

// TestAppRemovalResourceOwnershipDoesNotInheritRemovedAppFeature keeps shared Cache resources when a conventional removed App explicitly disabled Feature.
func TestAppRemovalResourceOwnershipDoesNotInheritRemovedAppFeature(t *testing.T) {
	_, config := appResourcePreflightFixture(t)
	config.Apps = map[string]project.AppConfig{"cache": {Components: project.Components{CLI: true, Cache: true}}}
	config.Dev.Apps = map[string]project.DevApp{"cache": {}}
	if err := writeProjectConfig(".goforj.yml", config); err != nil {
		t.Fatal(err)
	}
	writePrimitiveRendererFile(t, "app/cache/service.go", "package cache\n")
	owner := "package owner\nimport \"example.com/ownership/internal/caches\"\nfunc use(manager *caches.Manager) { _ = manager.Feature() }\n"
	writePrimitiveRendererFile(t, "internal/owner/service.go", owner)
	if _, err := generate.GenerateProjectFiles(".", generate.GenerationSelectionFromComponents(config.Render.Components)); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(readPrimitiveRendererFile(t, generate.CacheAccessorsPath), "Feature()") {
		t.Fatal("fixture lacks shared Cache resource")
	}
	if _, err := unitProjectRenderer(t).RemoveApp(project.DefaultNamedApp("cache")); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(readPrimitiveRendererFile(t, generate.CacheAccessorsPath), "Feature()") {
		t.Fatal("removed App claimed the shared Cache resource")
	}
	if readPrimitiveRendererFile(t, "internal/owner/service.go") != owner {
		t.Fatal("removal changed surviving owner source")
	}
}
