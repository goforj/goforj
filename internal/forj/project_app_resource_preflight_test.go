// TestAppResourceOwnershipRejectsSurvivingDependencies preserves every project byte and renderer config when an App claims an established name.
func TestAppResourceOwnershipRejectsSurvivingDependencies(t *testing.T) {
	tests := []struct {
		name, path, source string
		extra              map[string]string
	}{
		{name: "direct", source: "import \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager"},
		{name: "method value", source: "import \"example.com/ownership/internal/caches\"\nfunc use(m *caches.Manager) { _ = m.Feature }"},
		{name: "interface", source: "import \"example.com/ownership/internal/caches\"\nvar _ interface { Feature() any } = (*caches.Manager)(nil)"},
		{name: "dynamic", source: "import \"example.com/ownership/internal/caches\"\nfunc use(m *caches.Manager, name string) { _ = m.Get(name) }"},
		{name: "default only", source: "import \"example.com/ownership/internal/caches\"\nfunc use(m *caches.Manager) { _ = m.Default() }"},
		{name: "test source", path: "internal/owner/service_test.go", source: "import \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager"},
		{name: "build tags", source: "import \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager"},
		{name: "split package", source: "func use() { _ = manager.Feature }", extra: map[string]string{"internal/owner/dependency.go": "package owner\nimport \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager\n"}},
		{name: "wrapper", source: "import \"example.com/ownership/internal/wrapper\"\nvar manager = wrapper.Manager", extra: map[string]string{"internal/wrapper/service.go": "package wrapper\nimport \"example.com/ownership/internal/caches\"\nvar Manager *caches.Manager\n"}},
		{name: "split App factory", source: "func use() { _ = app.Caches() }", extra: map[string]string{
			"internal/owner/dependency.go": "package owner\nimport \"example.com/ownership/app/wire\"\nvar app, cleanup = wire.InitializeApplication()\n",
			"app/wire/app.go":              "// Code generated by GoForj CLI. DO NOT EDIT.\npackage wire\nimport \"example.com/ownership/internal/caches\"\ntype App struct { manager *caches.Manager }\n",
		}},
		{name: "app getter", source: "import \"example.com/ownership/app/wire\"\nfunc use(a *wire.App) { _ = a.Cache() }", extra: map[string]string{"app/wire/app.go": "// Code generated by GoForj CLI. DO NOT EDIT.\npackage wire\nimport \"example.com/ownership/internal/caches\"\ntype App struct { manager *caches.Manager }\n"}},
		{name: "generated suffix owner", path: "internal/owner/custom_gen.go", source: "import \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager"},
		{name: "generated string owner", source: "import \"example.com/ownership/internal/caches\"\nconst marker = \"// Code generated by GoForj CLI. DO NOT EDIT.\"\nvar manager *caches.Manager"},
		{name: "same package private field", path: "app/wire/custom.go", source: "func use(a *App) { _ = a.caches.Feature }"},
		{name: "same package App alias", path: "app/wire/custom.go", source: "type ownerApp App"},
		{name: "customized Wire harness getter", path: "app/wire/wire.go", source: "func use(a *App) { _ = a.Caches }"},
		{name: "customized Wire harness private field", path: "app/wire/wire.go", source: "func use(a *App) { _ = a.cache.Feature }"},
		{name: "same package App getter", path: "app/wire/custom.go", source: "func use(a *App) { _ = a.Cache }"},
		{name: "same package plural App getter", path: "app/wire/custom.go", source: "func use(a *App) { _ = a.Caches }"},
		{name: "unrecognized marked owner", path: "internal/owner/custom_gen.go", source: "import \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager"},
		{name: "owner inside manager", path: "internal/caches/custom.go", source: "var owner = (*Manager)(nil)"},
		{name: "markerless accessor", source: "var owner = true", extra: map[string]string{generate.CacheAccessorsPath: "package caches\n// Owner customization.\nfunc ownerManager(m *Manager) { _ = m.Feature }\n"}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root, config := appResourcePreflightFixture(t)
			path := test.path
			if path == "" {
				path = "internal/owner/service.go"
			}
			packageName := "owner"
			if strings.HasPrefix(path, "internal/caches/") {
				packageName = "caches"
			}
			if strings.HasPrefix(path, "app/wire/") {
				packageName = "wire"
			}
			source := "package " + packageName + "\n" + test.source + "\n"
			if test.name == "unrecognized marked owner" {
				source = "// Code generated by GoForj CLI. DO NOT EDIT.\n" + source
			}
			if strings.HasPrefix(test.name, "customized Wire harness") {
				source = "//go:build wireinject\n\n// GoForj Wire harness. Edit this file when customizing root assembly.\n" + source
			}
			if test.name == "build tags" {
				source = "//go:build unused_owner_tag\n\n" + source
			}
			writePrimitiveRendererFile(t, path, source)
			for path, source := range test.extra {
				writePrimitiveRendererFile(t, path, source)
			}
			renderer := unitProjectRenderer(t)
			renderer.config = config
			original := *config
			original.Apps = maps.Clone(config.Apps)
			before := appResourcePreflightSnapshot(t, root)
			err := renderer.RenderAppOnly(project.DefaultNamedApp("cache"), makeapp.RenderOptions{Components: project.Components{CLI: true, Feature: true}, SkipWire: true})
			if err == nil || !strings.Contains(err.Error(), "reconcile resource names and owner source") || !strings.Contains(err.Error(), "choose another App name") {
				t.Fatalf("guard error = %v", err)
			}
			if renderer.config != config || !reflect.DeepEqual(*config, original) {
				t.Fatal("rejected creation changed renderer configuration")
			}
			if after := appResourcePreflightSnapshot(t, root); !reflect.DeepEqual(before, after) {
				t.Fatal("rejected creation changed project files")
			}
		})
	}
}

// TestAppResourceOwnershipIgnoresUnrelatedSource prevents namespace checks from blocking owners outside the affected dependency family.
func TestAppResourceOwnershipIgnoresUnrelatedSource(t *testing.T) {
	for _, path := range []string{"internal/owner/service.go", "vendor/example/service.go", "_data/runtime/service.go"} {
		t.Run(path, func(t *testing.T) {
			_, _ = appResourcePreflightFixture(t)
			source := "package owner\nimport \"example.com/ownership/internal/features\"\nvar manager *features.Manager\n"
			if strings.HasPrefix(path, "vendor/") || strings.HasPrefix(path, "_data/") {
				source = "package owner\nimport \"example.com/ownership/internal/caches\"\nvar manager *caches.Manager\n"
			}
			writePrimitiveRendererFile(t, path, source)
			if err := unitProjectRenderer(t).RenderAppOnly(project.DefaultNamedApp("cache"), makeapp.RenderOptions{Components: project.Components{CLI: true, Feature: true}, SkipWire: true}); err != nil {
				t.Fatal(err)
			}
		})
	}
}

// TestAppResourceOwnershipPreservesCompilingCaller reproduces the original owner compile boundary before and after rejected creation.
func TestAppResourceOwnershipPreservesCompilingCaller(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles a generated owner fixture")
	}
	root, _ := appResourcePreflightFixture(t)
	writePrimitiveRendererFile(t, "go.mod", "module example.com/ownership\n\ngo 1.26.0\n\nrequire (\n github.com/goforj/cache v0.4.0\n github.com/goforj/cache/cachecore v0.4.3\n github.com/goforj/env/v2 v2.6.1\n github.com/goforj/str/v2 v2.0.1\n)\n")
	writePrimitiveRendererFile(t, "internal/owner/service.go", "package owner\nimport (\n \"example.com/ownership/internal/caches\"\n \"github.com/goforj/cache\"\n)\ntype Service struct { Caches *caches.Manager }\nfunc (s *Service) Cache() *cache.Cache { return s.Caches.Feature() }\n")
	if err := unitProjectRenderer(t).Render(ComponentRenderInput{renderAll: true}); err != nil {
		t.Fatal(err)
	}
	compile := func() {
		t.Helper()
		cmd := exec.Command("go", "test", "-mod=mod", "./internal/owner")
		cmd.Dir = root
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("owner compile: %v\n%s", err, output)
		}
	}
	compile()
	before := appResourcePreflightSnapshot(t, root)
	err := unitProjectRenderer(t).RenderAppOnly(project.DefaultNamedApp("cache"), makeapp.RenderOptions{Components: project.Components{CLI: true, Feature: true}, SkipWire: true})
	if err == nil {
		t.Fatal("creation unexpectedly accepted established caller")
	}
	if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
		t.Fatal("rejected creation changed project")
	}
	compile()
}

// appResourcePreflightFixture establishes the shared Cache registration before an App claims its prefix.
func appResourcePreflightFixture(t *testing.T) (string, *project.Config) {
	t.Helper()
	root := usePrimitiveRendererRoot(t)
	components := project.Components{CLI: true, Feature: true, Cache: true}
	config := &project.Config{ProjectName: "Ownership", GoModuleName: "example.com/ownership", Render: project.RenderConfig{Components: components}}
	if err := writeProjectConfig(".goforj.yml", config); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{".env.example", ".env"} {
		writePrimitiveRendererFile(t, path, "FEATURE_DRIVER=memory\nCACHE_DRIVER=memory\nCACHE_FEATURE_DRIVER=memory\n")
	}
	if _, err := generate.GenerateProjectFiles(".", generate.GenerationSelectionFromComponents(components)); err != nil {
		t.Fatal(err)
	}
	return root, config
}

// appResourcePreflightSnapshot captures all project files so rejected preflights cannot hide unrelated migration writes.
func appResourcePreflightSnapshot(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	if err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[path] = string(source)
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	return files
}

// TestAppResourceOwnershipTracksNestedScopes catches registration loss even when another App keeps the global accessor.
func TestAppResourceOwnershipTracksNestedScopes(t *testing.T) {
	tests := []struct {
		name, app, environment, manager string
		disableFeature                  bool
		apps                            map[string]project.AppConfig
	}{
		{name: "resource prefixed app", app: "cache-billing", environment: "FEATURE_DRIVER=memory\nCACHE_DRIVER=memory\nCACHE_BILLING_FEATURE_DRIVER=memory\n", manager: "caches"},
		{name: "feature prefixed app", app: "feature-feature", environment: "FEATURE_DRIVER=memory\nFEATURE_FEATURE_FEATURE_DRIVER=memory\n", manager: "features"},
		{name: "app registration with surviving global accessor", app: "billing", environment: "FEATURE_DRIVER=memory\nBILLING_FEATURE_CHECKOUT_DRIVER=memory\nREPORTS_FEATURE_CHECKOUT_DRIVER=memory\n", manager: "features", disableFeature: true, apps: map[string]project.AppConfig{"billing": {Components: project.Components{CLI: true, Feature: true}}, "reports": {Components: project.Components{CLI: true, Feature: true}}}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root, config := appResourcePreflightFixture(t)
			config.Apps = test.apps
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			for _, path := range []string{".env.example", ".env"} {
				writePrimitiveRendererFile(t, path, test.environment)
			}
			if _, err := generate.GenerateProjectFiles(".", generate.GenerationSelectionFromComponents(config.Render.Components)); err != nil {
				t.Fatal(err)
			}
			writePrimitiveRendererFile(t, "internal/owner/service.go", "package owner\nimport \"example.com/ownership/internal/"+test.manager+"\"\n")
			before := appResourcePreflightSnapshot(t, root)
			err := unitProjectRenderer(t).RenderAppOnly(project.DefaultNamedApp(test.app), makeapp.RenderOptions{Components: project.Components{CLI: true, Feature: !test.disableFeature}, SkipWire: true})
			if err == nil || !strings.Contains(err.Error(), "registration") {
				t.Fatalf("scope guard = %v", err)
			}
			if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
				t.Fatal("rejected scoped transition changed files")
			}
		})
	}
}

