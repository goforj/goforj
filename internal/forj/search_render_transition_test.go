// TestSearchDisabledRenderPreservesUnrelatedSource keeps upgrades compatible with existing business files and independent SDK use.
func TestSearchDisabledRenderPreservesUnrelatedSource(t *testing.T) {
	usePrimitiveRendererRoot(t)
	config := &project.Config{ProjectName: "Search transition", GoModuleName: "example.com/searchtransition", Render: project.RenderConfig{Components: project.Components{CLI: true}}}
	if err := writeProjectConfig(".goforj.yml", config); err != nil {
		t.Fatal(err)
	}
	sources := map[string]string{
		"app/search.go":                    "package app\nimport \"github.com/goforj/search\"\n// UserSchema describes an independently owned SDK schema.\nfunc UserSchema() search.Definition { return search.Definition{} }\n",
		"internal/searches/manager_gen.go": "package searches\n// BusinessSearch is unrelated to framework composition.\nfunc BusinessSearch() {}\n",
	}
	for path, source := range sources {
		writePrimitiveRendererFile(t, path, source)
	}
	writePrimitiveRendererFile(t, "go.mod", "module example.com/searchtransition\n")
	writePrimitiveRendererFile(t, ".env", "OWNER=keep\n")
	if err := unitProjectRenderer(t).Render(ComponentRenderInput{components: project.Components{CLI: true}}); err != nil {
		t.Fatalf("unrelated Search paths blocked render: %v", err)
	}
	for path, source := range sources {
		if got := readPrimitiveRendererFile(t, path); got != source {
			t.Fatalf("render changed independent source %s: %s", path, got)
		}
	}
}

// TestSearchRenderRemovalRefusesBeforeMutation protects actual schema declarations, generated resources, and Wire accessors.
func TestSearchRenderRemovalRefusesBeforeMutation(t *testing.T) {
	for _, test := range []struct{ name, path, source string }{
		{"generated manager", "internal/searches/manager_gen.go", "// Code generated by forj generate --search. DO NOT EDIT.\npackage searches\n"},
		{"App schema", "app/search.go", "package app\nimport \"github.com/goforj/search\"\nfunc SearchDefinitions() map[string]search.Definition { return nil }\n"},
		{"Wire accessor", "app/wire/app.go", "package wire\nimport \"example.com/searchtransition/internal/searches\"\ntype App struct{}\nfunc (app *App) Searches() *searches.Manager { return nil }\n"},
	} {
		t.Run(test.name, func(t *testing.T) {
			usePrimitiveRendererRoot(t)
			config := &project.Config{ProjectName: "Search transition", GoModuleName: "example.com/searchtransition", Render: project.RenderConfig{Components: project.Components{CLI: true, Search: true}}}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			writePrimitiveRendererFile(t, test.path, test.source)
			writePrimitiveRendererFile(t, "go.mod", "module example.com/searchtransition\n")
			writePrimitiveRendererFile(t, ".env", "SEARCH_DRIVER=bleve\nOWNER=keep\n")
			paths := []string{".goforj.yml", ".env", "go.mod", test.path}
			before := primitiveRendererFileHashes(t, paths)
			err := unitProjectRenderer(t).Render(ComponentRenderInput{components: project.Components{CLI: true}})
			if err == nil || !strings.Contains(err.Error(), "cannot disable Search") {
				t.Fatalf("removal=%v", err)
			}
			if !reflect.DeepEqual(before, primitiveRendererFileHashes(t, paths)) {
				t.Fatal("rejected Search removal changed owner files")
			}
		})
	}
}
