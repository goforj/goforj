// TestSearchGeneratedResidueRequiresLeadingMarker prevents examples and ordinary owner files from becoming framework ownership.
func TestSearchGeneratedResidueRequiresLeadingMarker(t *testing.T) {
	const marker = "// Code generated by forj generate --search. DO NOT EDIT."
	for _, test := range []struct {
		name, source string
		want         bool
	}{
		{"generated", marker + "\npackage searches\n", true},
		{"generated CRLF", marker + "\r\npackage searches\r\n", true},
		{"build constraint", "//go:build custom\n\n" + marker + "\npackage searches\n", true},
		{"unmarked", "package searches\nfunc Send() {}\n", false},
		{"string", "package searches\nconst example = `" + marker + "`\n", false},
		{"comment", "/*\n" + marker + "\n*/\npackage searches\n", false},
		{"suffix", marker + " is only an example\npackage searches\n", false},
	} {
		for _, name := range []string{"manager_gen.go", "accessors_gen.go"} {
			t.Run(test.name+"/"+name, func(t *testing.T) {
				root := usePrimitiveRendererRoot(t)
				config := &project.Config{Render: project.RenderConfig{Components: project.Components{CLI: true}}}
				if err := writeProjectConfig(".goforj.yml", config); err != nil {
					t.Fatal(err)
				}
				path := filepath.Join("internal", "searches", name)
				writePrimitiveRendererFile(t, path, test.source)
				renderer := unitProjectRenderer(t)
				got, err := renderer.workspace.searchGeneratedResiduePath()
				if err != nil || (got != "") != test.want {
					t.Fatalf("residue=%q, %v", got, err)
				}
				if test.want {
					before := appResourcePreflightSnapshot(t, root)
					err := renderer.Render(ComponentRenderInput{components: project.Components{CLI: true}})
					if err == nil || !strings.Contains(err.Error(), "cannot disable Search") {
						t.Fatalf("render=%v", err)
					}
					if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
						t.Fatal("rejected render changed files")
					}
				}
			})
		}
	}
}

// TestSearchAccessorPreflightDistinguishesSyntaxFromUnrelatedText requires the typed App getter rather than a matching name.
func TestSearchAccessorPreflightDistinguishesSyntaxFromUnrelatedText(t *testing.T) {
	const resourceImport = `import "example.com/app/internal/searches"; `
	for _, test := range []struct {
		name, source  string
		want, invalid bool
	}{
		{name: "missing"},
		{name: "typed", source: resourceImport + "type App struct{}; func (*App) Searches() *searches.Manager {return nil}", want: true},
		{name: "value receiver", source: resourceImport + "type App struct{}; func (App) Searches() *searches.Manager {return nil}", want: true},
		{name: "alias", source: `import senders "example.com/app/internal/searches"; type App struct{}; func (*App) Searches() *senders.Manager {return nil}`, want: true},
		{name: "dot", source: `import . "example.com/app/internal/searches"; type App struct{}; func (*App) Searches() *Manager {return nil}`, want: true},
		{name: "named result", source: resourceImport + "type App struct{}; func (*App) Searches() (manager *searches.Manager) {return nil}", want: true},
		{name: "unrelated receiver", source: resourceImport + "type Observer struct{}; func (*Observer) Searches() *searches.Manager {return nil}"},
		{name: "unrelated observer", source: "type Observer struct{}; func (*Observer) Searches() []string {return nil}"},
		{name: "any result", source: "type App struct{}; func (*App) Searches() any {return nil}"},
		{name: "string result", source: "type App struct{}; func (*App) Searches() string {return \"business\"}"},
		{name: "method parameter", source: resourceImport + "type App struct{}; func (*App) Searches(manager *searches.Manager) *searches.Manager {return nil}"},
		{name: "variadic parameter", source: resourceImport + "type App struct{}; func (*App) Searches(manager ...*searches.Manager) *searches.Manager {return nil}"},
		{name: "no result", source: "type App struct{}; func (*App) Searches() {}"},
		{name: "multiple results", source: resourceImport + "type App struct{}; func (*App) Searches() (*searches.Manager, error) {return nil, nil}"},
		{name: "grouped results", source: resourceImport + "type App struct{}; func (*App) Searches() (first, second *searches.Manager) {return nil, nil}"},
		{name: "double pointer", source: resourceImport + "type App struct{}; func (*App) Searches() **searches.Manager {return nil}"},
		{name: "value result", source: resourceImport + "type App struct{}; func (*App) Searches() searches.Manager {panic(0)}"},
		{name: "unrelated import", source: `import "example.com/business/searches"; type App struct{}; func (*App) Searches() *searches.Manager {return nil}`},
		{name: "blank import", source: `import _ "example.com/app/internal/searches"; type App struct{}; func (*App) Searches() *searches.Manager {return nil}`},
		{name: "free function", source: resourceImport + "func Searches() *searches.Manager {return nil}"},
		{name: "comments", source: "// func (*App) Searches() *searches.Manager {return nil}\n"},
		{name: "strings", source: "const source = `func (*App) Searches() *searches.Manager {return nil}`"},
		{name: "invalid", source: "func (", invalid: true},
	} {
		t.Run(test.name, func(t *testing.T) {
			path := filepath.Join(test.name, "app.go")
			file, err := parser.ParseFile(token.NewFileSet(), path, "package wire\n"+test.source, 0)
			got := false
			if err == nil {
				got = searchManagerAccessor(file)
			}
			if got != test.want || (err != nil) != test.invalid {
				t.Fatalf("accessor = %v, %v", got, err)
			}
		})
	}
}

// TestSearchLastAppRemovalOwnership distinguishes generated residue from a remaining owner namespace after explicit cleanup.
func TestSearchLastAppRemovalOwnership(t *testing.T) {
	for _, test := range []struct {
		name, path, source string
		blocked            bool
	}{
		{"owner package", "internal/searches/custom.go", "package searches\nfunc BusinessSearch() {}\n", false},
		{"unmarked manager", "internal/searches/manager_gen.go", "package searches\nfunc BusinessSearch() {}\n", false},
		{"embedded marker", "internal/searches/manager_gen.go", "package searches\nconst marker = `// Code generated by forj generate --search. DO NOT EDIT.`\n", false},
		{"unrelated receiver", "app/billing/wire/app.go", "package wire\nimport \"example.com/searchtransition/internal/searches\"\ntype Observer struct{}\nfunc (*Observer) Searches() *searches.Manager {return nil}\n", false},
		{"generated manager", "internal/searches/manager_gen.go", "// Code generated by forj generate --search. DO NOT EDIT.\npackage searches\n", true},
		{"generated accessors", "internal/searches/accessors_gen.go", "//go:build custom\n\n// Code generated by forj generate --search. DO NOT EDIT.\r\npackage searches\n", true},
		{"typed accessor", "app/billing/wire/app.go", "package wire\nimport \"example.com/searchtransition/internal/searches\"\ntype App struct{}\nfunc (*App) Searches() *searches.Manager {return nil}\n", true},
	} {
		t.Run(test.name, func(t *testing.T) {
			root := usePrimitiveRendererRoot(t)
			app := project.DefaultNamedApp("billing")
			config := &project.Config{ProjectName: "Search transition", GoModuleName: "example.com/searchtransition", Render: project.RenderConfig{Components: project.Components{CLI: true}}, Apps: map[string]project.AppConfig{app.Name: {Components: project.Components{CLI: true, Search: true}}}}
			if err := writeProjectConfig(".goforj.yml", config); err != nil {
				t.Fatal(err)
			}
			writePrimitiveRendererFile(t, test.path, test.source)
			before := appResourcePreflightSnapshot(t, root)
			result, err := unitProjectRenderer(t).RemoveApp(app)
			if test.blocked {
				if err == nil || !strings.Contains(err.Error(), "last App using Search") || result.Changed() {
					t.Fatalf("removal=%#v, %v", result, err)
				}
				if !reflect.DeepEqual(before, appResourcePreflightSnapshot(t, root)) {
					t.Fatal("rejected removal changed files")
				}
			} else {
				if err != nil {
					t.Fatal(err)
				}
				if strings.HasPrefix(test.path, "internal/") && readPrimitiveRendererFile(t, test.path) != test.source {
					t.Fatal("removal changed owner source")
				}
			}
		})
	}
}
