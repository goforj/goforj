#!/usr/bin/env bash

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
fixture_root="$(mktemp -d)"
trap 'rm -rf "$fixture_root"' EXIT

# make_fixture keeps manifest discovery real while isolating every case from the checkout.
make_fixture() {
  local name="$1"
  local fixture="$fixture_root/$name"
  mkdir -p "$fixture/scripts" "$fixture/.github" "$fixture/integration" "$fixture/frontend"
  cp "$script_dir/check-security-inventory.sh" "$fixture/scripts/check-security-inventory.sh"
  printf 'module example.com/inventory\n\ngo 1.26.0\n' > "$fixture/go.mod"
  printf 'module example.com/inventory/integration\n\ngo 1.26.0\n' > "$fixture/integration/go.mod"
  printf '{}\n' > "$fixture/package-lock.json"
  printf '{}\n' > "$fixture/frontend/package-lock.json"
  cat > "$fixture/.github/dependabot.yml"
}

# expect_success requires complete coverage of both module and lockfile surfaces.
expect_success() {
  local name="$1"
  if ! bash "$fixture_root/$name/scripts/check-security-inventory.sh" > "$fixture_root/$name/output" 2>&1; then
    cat "$fixture_root/$name/output" >&2
    echo "$name: expected complete security coverage" >&2
    exit 1
  fi
}

# expect_failure ensures one ecosystem cannot silently satisfy another ecosystem's coverage.
expect_failure() {
  local name="$1"
  local message="$2"
  if bash "$fixture_root/$name/scripts/check-security-inventory.sh" > "$fixture_root/$name/output" 2>&1; then
    echo "$name: expected missing coverage to fail" >&2
    exit 1
  fi
  if ! grep -Fq "$message" "$fixture_root/$name/output"; then
    cat "$fixture_root/$name/output" >&2
    echo "$name: failed for an unexpected reason" >&2
    exit 1
  fi
}

make_fixture legacy <<'YAML'
version: 2
updates:
  - package-ecosystem: gomod
    directory: /
  - package-ecosystem: gomod
    directory: /integration
  - package-ecosystem: npm
    directory: /
  - package-ecosystem: npm
    directory: /frontend
YAML
expect_success legacy

make_fixture grouped <<'YAML'
version: 2
updates:
  - package-ecosystem: "gomod"
    directories:
      - "/"
      # Nested modules remain independently owned dependency surfaces.

      - '/integration'
    schedule:
      interval: monthly
  - package-ecosystem: npm
    directories:
      - /
      - /frontend
    schedule:
      interval: monthly
YAML
expect_success grouped

make_fixture missing_go <<'YAML'
version: 2
updates:
  - package-ecosystem: gomod
    directories:
      - /
  - package-ecosystem: npm
    directories:
      - /
      - /integration
      - /frontend
YAML
expect_failure missing_go 'missing Dependabot coverage for gomod manifest:'

make_fixture missing_npm <<'YAML'
version: 2
updates:
  - package-ecosystem: gomod
    directories:
      - /
      - /integration
      - /frontend
  - package-ecosystem: npm
    directory: /
YAML
expect_failure missing_npm 'missing Dependabot coverage for npm manifest:'

make_fixture generated <<'YAML'
version: 2
updates:
  - package-ecosystem: gomod
    directory: /
  - package-ecosystem: npm
    directories:
      - /
      - /frontend
YAML
printf '// Code generated by the fixture generator; DO NOT EDIT.\nmodule example.com/generated\n\ngo 1.26.0\n' > "$fixture_root/generated/integration/go.mod"
expect_success generated

echo "security inventory fixtures passed"
